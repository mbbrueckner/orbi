#!/usr/bin/env python3
"""Converts the sprite PNGs into a C file for LVGL 8 (RGB565 + alpha).

Usage (from the project root):
    python3 tools/gen_sprites.py

Reads  components/ui/assets/sprites/raccoon_<set>_<frame>.png
Writes components/ui/sprites_data.c

The pixel format matches sdkconfig.defaults (16 bit colour, swapped bytes):
per pixel the two colour bytes (high byte first) followed by one alpha byte.
Needs Pillow (pip install pillow). The generated file is committed, so a
normal build does not need Python.
"""

import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "components/ui/assets/sprites"
OUT = ROOT / "components/ui/sprites_data.c"

# Order must match sprite_set_t in sprites.h.
SETS = ["happy", "hungry", "tired", "sad", "sleep"]


def pixel_bytes(img):
    out = bytearray()
    for r, g, b, a in img.convert("RGBA").getdata():
        rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((rgb565 >> 8, rgb565 & 0xFF, a))
    return out


def frames_of(name):
    files = []
    for f in SRC.glob(f"raccoon_{name}_*.png"):
        m = re.fullmatch(rf"raccoon_{name}_(\d+)\.png", f.name)
        if m:
            files.append((int(m.group(1)), f))
    return [f for _, f in sorted(files)]


def main():
    lines = [
        "/* Generated by tools/gen_sprites.py. Do not edit. */",
        "",
        '#include "sprites.h"',
        "",
    ]
    tables = []
    for name in SETS:
        frames = frames_of(name)
        if not frames:
            sys.exit(f"no frames found for set '{name}'")
        names = []
        for i, f in enumerate(frames, start=1):
            img = Image.open(f)
            if img.size != (SPRITE_SIZE := 80, 80):
                sys.exit(f"{f.name}: expected 80x80, got {img.size}")
            data = pixel_bytes(img)
            sym = f"raccoon_{name}_{i}"
            lines.append(f"static const uint8_t {sym}_map[] = {{")
            for k in range(0, len(data), 24):
                chunk = ", ".join(f"0x{b:02X}" for b in data[k:k + 24])
                lines.append(f"  {chunk},")
            lines.append("};")
            lines.append(f"static const lv_img_dsc_t {sym} = {{")
            lines.append("  .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,")
            lines.append(f"  .header.w = {img.width},")
            lines.append(f"  .header.h = {img.height},")
            lines.append(f"  .data_size = {len(data)},")
            lines.append(f"  .data = {sym}_map,")
            lines.append("};")
            lines.append("")
            names.append(sym)
        tables.append((name, names))

    for name, names in tables:
        lines.append(f"static const lv_img_dsc_t* const frames_{name}[] = {{")
        lines += [f"  &{n}," for n in names]
        lines.append("};")
        lines.append("")

    lines.append("static const struct {")
    lines.append("  const lv_img_dsc_t* const* frames;")
    lines.append("  int count;")
    lines.append("} sets[SPRITE_SET_COUNT] = {")
    for name, names in tables:
        lines.append(f"  [SPRITE_{name.upper()}] = {{frames_{name}, {len(names)}}},")
    lines.append("};")
    lines.append("")
    lines.append("int sprites_frame_count(sprite_set_t set) {")
    lines.append("  return sets[set].count;")
    lines.append("}")
    lines.append("")
    lines.append("const lv_img_dsc_t* sprites_get(sprite_set_t set, int frame) {")
    lines.append("  return sets[set].frames[frame % sets[set].count];")
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines))
    total = sum(len(n) for _, n in tables)
    print(f"wrote {OUT.relative_to(ROOT)} ({total} frames)")


if __name__ == "__main__":
    main()
